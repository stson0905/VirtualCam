const fs = require('fs');
const os = require('os');
const path = require('path');
const yaml = require('js-yaml');
const { v5: uuidv5 } = require('uuid');
const { resolveFfmpegPath, resolveFfprobePath } = require('./rtspServer/ffmpegLocator');
const { resolveMediamtxPath } = require('./rtspServer/mediamtxLocator');
const { probeVideoStream } = require('./rtspServer/sourceProbe');
const { baseDir } = require('./baseDir');
const logger = require('./logger');

// Fixed namespace used only to derive a stable per-device UUID from each
// camera's MAC address in config.yaml. It has no meaning outside this project.
const DEVICE_UUID_NAMESPACE = '6ba7b810-9dad-11d1-80b4-00c04fd430c8';

function detectFirstExternalIPv4() {
  const interfaces = os.networkInterfaces();
  for (const name of Object.keys(interfaces)) {
    for (const iface of interfaces[name]) {
      if (iface.family === 'IPv4' && !iface.internal) {
        return iface.address;
      }
    }
  }
  return '127.0.0.1';
}

function deepMerge(base, override) {
  if (!override) return base;
  const result = { ...base };
  for (const key of Object.keys(override)) {
    const val = override[key];
    if (val && typeof val === 'object' && !Array.isArray(val) && base[key] && typeof base[key] === 'object') {
      result[key] = deepMerge(base[key], val);
    } else {
      result[key] = val;
    }
  }
  return result;
}

function buildCamera(index, doc, advertiseAddress, rtspServerPort, auth) {
  const gen = doc.cameras;
  const defaults = doc.cameraDefaults;
  const override = (gen.overrides && gen.overrides[String(index)]) || {};

  const base = {
    name: `${gen.namePrefix} ${index}`,
    mac: `${gen.macPrefix}${index.toString(16).padStart(2, '0')}`,
    serialNumber: `${gen.serialPrefix}${String(index).padStart(4, '0')}`,
    manufacturer: defaults.manufacturer,
    model: defaults.model,
    firmwareVersion: defaults.firmwareVersion,
    hardwareId: defaults.hardwareId,
    location: defaults.location,
    httpPort: gen.httpPortStart + index - 1,
    rtspPath: `${gen.rtspPathPrefix}${index}`,
    stream: { ...defaults.stream },
    source: { ...defaults.source },
  };

  const merged = deepMerge(base, override);

  // Track whether source.file came from the auto {n}-substitution pattern
  // (rather than an explicit path in config.yaml) - if the file turns out
  // missing, this tells us it's most likely a cameras.count / actual video
  // file count mismatch, not a typo'd path, so we can say so plainly.
  let sourceFileAutoGenerated = false;
  if (merged.source.type === 'file' && !merged.source.file && gen.sourceFilePattern) {
    merged.source.file = gen.sourceFilePattern.replace('{n}', index);
    sourceFileAutoGenerated = true;
  }

  if (merged.source.type === 'file') {
    if (!merged.source.file) {
      throw new Error(`camera ${index}: source.type is "file" but source.file is empty (and no cameras.sourceFilePattern set)`);
    }
    // Relative paths (e.g. ".\cam\ch1.mp4") resolve against the app's own
    // folder rather than the current working directory, so config.yaml keeps
    // working no matter where the app is launched from (double-click, a
    // shortcut, a different cwd, ...).
    if (!path.isAbsolute(merged.source.file)) {
      merged.source.file = path.join(baseDir, merged.source.file);
    }
    if (!fs.existsSync(merged.source.file)) {
      if (sourceFileAutoGenerated) {
        throw new Error(
          `camera ${index}: 영상 파일을 찾을 수 없습니다 - ${merged.source.file}\n` +
            `  => cameras.count(=${gen.count})가 실제로 준비된 영상 파일 개수보다 큰 것 같습니다.\n` +
            `     이 파일이 있는 폴더에 ch1${path.extname(merged.source.file)} ~ ch${gen.count}${path.extname(merged.source.file)} 파일을 모두 채워 넣거나,\n` +
            `     config.yaml의 cameras.count를 실제 준비된 영상 파일 개수에 맞게 줄여주세요.`
        );
      }
      throw new Error(`camera ${index}: source file not found: ${merged.source.file}`);
    }
  }

  return {
    device: {
      name: merged.name,
      manufacturer: merged.manufacturer,
      model: merged.model,
      firmwareVersion: merged.firmwareVersion,
      serialNumber: merged.serialNumber,
      hardwareId: merged.hardwareId,
      location: merged.location,
      mac: merged.mac,
    },
    endpointUuid: uuidv5(merged.mac, DEVICE_UUID_NAMESPACE),
    network: { advertiseAddress, httpPort: merged.httpPort },
    stream: { ...merged.stream, rtspUrl: `rtsp://${advertiseAddress}:${rtspServerPort}${merged.rtspPath}` },
    rtspPath: merged.rtspPath,
    source: merged.source,
    auth,
  };
}

// Earlier revisions of this file also refused to stream-copy a source unless
// its H.264 profile was Baseline/Constrained Baseline, on the theory that a
// "connects but shows nothing, only in one particular viewer" report was
// caused by non-Baseline (CABAC) content. That turned out to be a red
// herring - packet-level comparison against a real camera showed the actual
// difference was mediamtx always packing SPS+PPS into a STAP-A RTP packet
// (see rtspH264CompatProxy.js for the real fix, which now unpacks that for
// every stream regardless of source profile). Gating stream-copy on profile
// was pure CPU cost with no remaining benefit once that proxy exists, so it
// was removed - any H.264 source can be stream-copied again.

// A file source that's already H264 can be published to mediamtx via RTSP
// stream-copy (remux only, no decode/encode) instead of a full software
// libx264 re-encode - this is by far the biggest CPU cost in the app, since
// one ffmpeg process runs per camera. When we take that path, the encoder
// never runs, so it can't apply the configured width/height/frameRate/
// bitrateKbps; we overwrite those with the file's real values instead so
// the ONVIF-reported profile (GetProfiles/GetVideoSources) matches what's
// actually being streamed, rather than silently lying about it.
function applyStreamCopyDecision(camera, ffprobePath) {
  if (camera.source.type !== 'file') return;
  camera.source.copyMode = false;

  if (camera.source.forceEncode) {
    logger.info(`[Config] camera ${camera.device.name}: source.forceEncode is set, using software encode`);
    return;
  }

  const probed = probeVideoStream(ffprobePath, camera.source.file);
  if (!probed) {
    logger.warn(`[Config] camera ${camera.device.name}: could not probe source file (ffprobe missing or failed) - using software encode`);
    return;
  }
  if (probed.codec !== 'h264') {
    logger.info(`[Config] camera ${camera.device.name}: source codec is "${probed.codec}", not H264 - using software encode`);
    return;
  }

  camera.source.copyMode = true;
  camera.stream.width = probed.width;
  camera.stream.height = probed.height;
  // ONVIF's RateControl/FrameRateLimit (and VideoSource/Framerate) are typed
  // as xs:int in the schema - a decimal here (e.g. ffprobe's 29.99 for a
  // 30000/1001-style rate) makes strict SOAP clients like ODM fail to
  // deserialize the GetProfiles/GetVideoSources reply, so this must round
  // to a whole number, not just a couple of decimal places.
  if (probed.frameRate > 0) camera.stream.frameRate = Math.round(probed.frameRate);
  if (probed.bitrateKbps) camera.stream.bitrateKbps = probed.bitrateKbps;
  logger.info(
    `[Config] camera ${camera.device.name}: source is already H264 (${probed.width}x${probed.height}) - ` +
      `using RTSP stream copy, no re-encode (CPU-cheap)`
  );
}

function loadConfig(configPath = path.join(baseDir, 'config.yaml')) {
  const raw = fs.readFileSync(configPath, 'utf8');
  const doc = yaml.load(raw);

  const advertiseAddress =
    !doc.network.advertiseAddress || doc.network.advertiseAddress === 'auto'
      ? detectFirstExternalIPv4()
      : doc.network.advertiseAddress;

  const auth = doc.auth || { enabled: false };
  const rtspServer = doc.rtspServer || { enabled: false };

  if (rtspServer.enabled) {
    rtspServer.ffmpegPath = resolveFfmpegPath(rtspServer.ffmpegPath);
    rtspServer.mediamtxPath = resolveMediamtxPath(rtspServer.mediamtxPath);
    rtspServer.ffprobePath = resolveFfprobePath(rtspServer.ffmpegPath);
  }

  const count = doc.cameras.count;
  const cameras = [];
  for (let i = 1; i <= count; i++) {
    cameras.push(buildCamera(i, doc, advertiseAddress, rtspServer.port, auth));
  }

  if (rtspServer.enabled) {
    for (const camera of cameras) {
      applyStreamCopyDecision(camera, rtspServer.ffprobePath);
    }
  }

  return {
    cameras,
    rtspServer,
    auth,
    network: {
      discoveryPort: doc.network.discoveryPort || 3702,
      advertiseAddress,
    },
  };
}

module.exports = { loadConfig };
